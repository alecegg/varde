import com.sun.source.tree.CompilationUnitTree;
import com.sun.source.tree.IdentifierTree;
import com.sun.source.tree.MemberSelectTree;
import com.sun.source.tree.MethodInvocationTree;
import com.sun.source.tree.MethodTree;
import com.sun.source.tree.NewClassTree;
import com.sun.source.tree.Tree;
import com.sun.source.util.JavacTask;
import com.sun.source.util.SourcePositions;
import com.sun.source.util.TreePathScanner;
import com.sun.source.util.TreePath;
import com.sun.source.util.Trees;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import javax.lang.model.element.Element;
import javax.lang.model.element.ExecutableElement;
import javax.lang.model.element.ElementKind;
import javax.lang.model.element.Modifier;
import javax.lang.model.element.TypeElement;
import javax.lang.model.type.DeclaredType;
import javax.lang.model.type.TypeMirror;
import javax.tools.DiagnosticCollector;
import javax.tools.JavaCompiler;
import javax.tools.JavaFileObject;
import javax.tools.StandardJavaFileManager;
import javax.tools.ToolProvider;

/**
 * Match rule: emit the compiler-selected declaration, including an overridden or
 * implemented declaration, rather than guessing the runtime override. Only
 * reflection is dynamic/unknown; calls through functional-interface values are
 * higher-order/unknown because the value's implementation is not statically fixed.
 */
public final class JavacTargets {
  private JavacTargets() {}

  public static void main(String[] args) throws Exception {
    if (args.length != 3) {
      throw new IllegalArgumentException("usage: JavacTargets <repo> <repo-root> <source-root>");
    }
    Path repoRoot = Path.of(args[1]).toAbsolutePath().normalize();
    Path sourceRoot = Path.of(args[2]).toAbsolutePath().normalize();
    List<Path> sources;
    try (var paths = Files.walk(sourceRoot)) {
      sources = paths.filter(path -> path.toString().endsWith(".java"))
          .sorted().toList();
    }
    if (sources.isEmpty()) {
      throw new IllegalArgumentException("source root has no Java files: " + sourceRoot);
    }
    JavaCompiler compiler = ToolProvider.getSystemJavaCompiler();
    DiagnosticCollector<JavaFileObject> diagnostics = new DiagnosticCollector<>();
    Path classes = Files.createTempDirectory("javac-call-audit-");
    try (StandardJavaFileManager manager = compiler.getStandardFileManager(
        diagnostics, null, StandardCharsets.UTF_8)) {
      Iterable<? extends JavaFileObject> units = manager.getJavaFileObjectsFromPaths(sources);
      List<String> options = List.of("-proc:none", "-Xlint:none", "-d", classes.toString());
      JavacTask task = (JavacTask) compiler.getTask(null, manager, diagnostics, options, null, units);
      List<CompilationUnitTree> parsed = new ArrayList<>();
      task.parse().forEach(parsed::add);
      task.analyze();
      Trees trees = Trees.instance(task);
      SourcePositions positions = trees.getSourcePositions();
      for (CompilationUnitTree unit : parsed) {
        Path source = Path.of(unit.getSourceFile().toUri()).toAbsolutePath().normalize();
        if (isGenerated(source)) continue;
        new Calls(args[0], repoRoot, unit, trees, positions, source).scan(unit, null);
      }
    } finally {
      deleteTree(classes);
    }
  }

  /** Generated sources are excluded from the audit sample (design decision D6). */
  private static boolean isGenerated(Path source) {
    String path = source.toString().replace('\\', '/');
    if (path.matches(".*/(gen|generated|target|build)/.*")) {
      return true;
    }
    try {
      List<String> lines = Files.readAllLines(source, StandardCharsets.UTF_8);
      List<String> head = lines.subList(0, Math.min(8, lines.size()));
      for (String line : head) {
        if (line.contains("@Generated") || line.contains("Generated by")
            || line.contains("DO NOT EDIT")) {
          return true;
        }
      }
    } catch (IOException | IndexOutOfBoundsException ignored) {
      return false;
    }
    return false;
  }

  private static final class Calls extends TreePathScanner<Void, Void> {
    private final String repo;
    private final Path repoRoot;
    private final CompilationUnitTree unit;
    private final Trees trees;
    private final SourcePositions positions;
    private final Path source;
    private String caller;

    Calls(String repo, Path repoRoot, CompilationUnitTree unit, Trees trees,
        SourcePositions positions, Path source) {
      this.repo = repo;
      this.repoRoot = repoRoot;
      this.unit = unit;
      this.trees = trees;
      this.positions = positions;
      this.source = source;
    }

    @Override
    public Void visitMethod(MethodTree tree, Void unused) {
      String previous = caller;
      Element element = trees.getElement(getCurrentPath());
      caller = element instanceof ExecutableElement
          ? methodId(source, (ExecutableElement) element) : null;
      Void result = super.visitMethod(tree, unused);
      caller = previous;
      return result;
    }

    @Override
    public Void visitMethodInvocation(MethodInvocationTree tree, Void unused) {
      emit(tree, "method");
      return super.visitMethodInvocation(tree, unused);
    }

    @Override
    public Void visitNewClass(NewClassTree tree, Void unused) {
      emit(tree, "constructor");
      return super.visitNewClass(tree, unused);
    }

    private void emit(Tree tree, String kind) {
      Element element = trees.getElement(getCurrentPath());
      boolean reflective = element instanceof ExecutableElement
          && isReflective((ExecutableElement) element);
      boolean higherOrder = element instanceof ExecutableElement
          && isFunctionalCall((ExecutableElement) element);
      boolean constructor = element instanceof ExecutableElement
          && element.getKind() == ElementKind.CONSTRUCTOR;
      String target = element instanceof ExecutableElement && !reflective
          && !higherOrder
          ? targetId((ExecutableElement) element) : null;
      Path targetFile = sourceFile(element);
      boolean receiver = tree instanceof MethodInvocationTree
          && ((MethodInvocationTree) tree).getMethodSelect() instanceof MemberSelectTree;
      String callClass = higherOrder ? "higher_order"
          : reflective ? "dynamic"
          : constructor ? "constructor"
          : targetFile != null && !targetFile.equals(source) ? "imported"
          : receiver ? "member" : "same_file";
      boolean projectTarget = targetFile != null && targetFile.startsWith(repoRoot);
      String truthTarget = projectTarget ? target : null;
      String targetKind = reflective || higherOrder ? "dynamic"
          : target == null ? null : projectTarget ? "project" : "external";
      long offset = positions.getStartPosition(unit, tree);
      long line = unit.getLineMap().getLineNumber(offset);
      String relative = repoRoot.relativize(source).toString().replace('\\', '/');
      String module = unit.getPackageName() == null ? parent(relative)
          : unit.getPackageName().toString();
      String targetModule = targetFile == null || !targetFile.startsWith(repoRoot)
          ? null : packageName(element, targetFile);
      System.out.println("{\"repo\":" + quote(repo)
          + ",\"file\":" + quote(relative)
          + ",\"line\":" + line
          + ",\"call_class\":" + quote(callClass)
          + ",\"call_name\":" + quote(callName(tree, element))
          + ",\"target\":" + nullable(truthTarget)
          + ",\"target_kind\":" + nullable(targetKind)
          + ",\"caller\":" + nullable(caller)
          + ",\"module\":" + quote(module)
          + ",\"target_module\":" + nullable(targetModule)
          + ",\"truth_source\":" + quote("javac:" + System.getProperty("java.version")) + "}");
    }

    private Path sourceFile(Element element) {
      if (element == null) return null;
      TreePath path = trees.getPath(element);
      if (path == null) return null;
      try {
        return Path.of(path.getCompilationUnit().getSourceFile().toUri())
            .toAbsolutePath().normalize();
      } catch (Exception ignored) {
        return null;
      }
    }

    private String callName(Tree tree, Element element) {
      if (tree instanceof MethodInvocationTree) {
        Tree select = ((MethodInvocationTree) tree).getMethodSelect();
        if (select instanceof IdentifierTree) {
          String name = ((IdentifierTree) select).getName().toString();
          if (name.equals("this") || name.equals("super")) return name;
        }
      }
      if (element instanceof ExecutableElement
          && element.getKind() == ElementKind.CONSTRUCTOR) {
        String owner = constructorOwner((ExecutableElement) element);
        if (!owner.isEmpty()) return owner;
      }
      if (element instanceof ExecutableElement) {
        String name = element.getSimpleName().toString();
        if (!name.isEmpty()) return name;
      }
      if (tree instanceof NewClassTree) {
        String identifier = ((NewClassTree) tree).getIdentifier().toString();
        if (!identifier.isEmpty()) return identifier;
      }
      String text = tree.toString();
      return text.isEmpty() ? "unknown" : text;
    }

    /** The called constructor's name: its type, or the extended type when anonymous. */
    private String constructorOwner(ExecutableElement constructor) {
      if (!(constructor.getEnclosingElement() instanceof TypeElement type)) return "";
      String name = type.getSimpleName().toString();
      if (!name.isEmpty()) return name;
      TypeMirror parent = type.getSuperclass();
      if (parent instanceof DeclaredType declared
          && declared.asElement() instanceof TypeElement superType
          && !superType.getQualifiedName().contentEquals("java.lang.Object")) {
        return superType.getSimpleName().toString();
      }
      for (TypeMirror implemented : type.getInterfaces()) {
        if (implemented instanceof DeclaredType declared
            && declared.asElement() instanceof TypeElement interfaceType) {
          return interfaceType.getSimpleName().toString();
        }
      }
      return "";
    }

    private String packageName(Element element, Path file) {
      TreePath path = trees.getPath(element);
      if (path == null || path.getCompilationUnit().getPackageName() == null) {
        return parent(repoRoot.relativize(file).toString().replace('\\', '/'));
      }
      return path.getCompilationUnit().getPackageName().toString();
    }

    /**
     * The reflection surface: a call whose real target is a member reached
     * through reflection metadata rather than named at the call site.
     */
    private boolean isReflective(ExecutableElement method) {
      Element owner = method.getEnclosingElement();
      if (!(owner instanceof TypeElement)) return false;
      String type = ((TypeElement) owner).getQualifiedName().toString();
      String name = method.getSimpleName().toString();
      return switch (type) {
        case "java.lang.reflect.Method" -> name.equals("invoke");
        case "java.lang.reflect.Constructor" -> name.equals("newInstance");
        case "java.lang.reflect.Field" -> name.equals("get") || name.equals("set");
        case "java.lang.Class" -> name.equals("newInstance");
        case "java.lang.invoke.MethodHandle" -> name.equals("invoke")
            || name.equals("invokeExact") || name.equals("invokeWithArguments");
        default -> false;
      };
    }

    private boolean isFunctionalCall(ExecutableElement method) {
      if (!(method.getEnclosingElement() instanceof TypeElement)) return false;
      TypeElement owner = (TypeElement) method.getEnclosingElement();
      if (owner.getKind() != ElementKind.INTERFACE) return false;
      long abstractMethods = owner.getEnclosedElements().stream()
          .filter(element -> element instanceof ExecutableElement)
          .filter(element -> element.getModifiers().contains(Modifier.ABSTRACT))
          .count();
      return abstractMethods == 1;
    }

    private String targetId(ExecutableElement method) {
      if (method.getKind() == ElementKind.CONSTRUCTOR
          && method.getEnclosingElement() instanceof TypeElement
          && ((TypeElement) method.getEnclosingElement()).getQualifiedName().length() == 0) {
        return null;
      }
      Path path = sourceFile(method);
      return methodId(path == null ? source : path, method);
    }

    private String methodId(Path file, ExecutableElement method) {
      Element owner = method.getEnclosingElement();
      String name = owner instanceof TypeElement
          ? ((TypeElement) owner).getQualifiedName().toString()
          : owner.toString();
      if (name.isEmpty()) name = "<anonymous>";
      String parameters = method.getParameters().stream()
          .map(parameter -> parameter.asType().toString())
          .reduce((left, right) -> left + "," + right).orElse("");
      return repoRoot.relativize(file).toString().replace('\\', '/') + "::" + name
          + "." + method.getSimpleName() + "(" + parameters + ")";
    }
  }

  private static String parent(String path) {
    int index = path.lastIndexOf('/');
    return index < 0 ? "" : path.substring(0, index);
  }

  private static String nullable(String value) {
    return value == null ? "null" : quote(value);
  }

  private static String quote(String value) {
    return "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"")
        .replace("\n", "\\n").replace("\r", "\\r") + "\"";
  }

  private static void deleteTree(Path root) throws IOException {
    try (var paths = Files.walk(root)) {
      for (Path path : paths.sorted(Comparator.reverseOrder()).toList()) Files.deleteIfExists(path);
    }
  }
}
