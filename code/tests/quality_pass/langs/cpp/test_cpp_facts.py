from varde_code.quality_pass.facts import extract_facts


def test_template_parameters_are_counted_without_name_penalty():
    facts = extract_facts(
        "template<class T> T identity(T value) { return value; }", "cpp"
    )

    assert facts["functions"][0]["params"] == 1
    assert facts["functions"][0]["name_issues"] == []


def test_const_and_mutable_overloads_remain_separate_functions():
    facts = extract_facts(
        "struct Box { int get() { return 1; } int get() const { return 1; } };",
        "cpp",
    )

    getters = [row for row in facts["functions"] if row["name"] == "get"]
    assert len(getters) == 2
    assert [row["params"] for row in getters] == [0, 0]


def test_macro_function_parameters_are_counted_without_name_penalty():
    facts = extract_facts(
        "#define APPLY(x) ((x) + 1)\nint f(int x) { return APPLY(x); }", "cpp"
    )

    assert facts["functions"]
    assert facts["functions"][0]["params"] == 1
    assert "unmeasured_template_or_macro" not in facts["functions"][0]["name_issues"]


def test_parameter_shapes_cover_defaults_variadics_void_and_wrappers():
    facts = extract_facts(
        "int defaulted(int value = 1) { return value; }\n"
        "int variadic(int value, ...) { return value; }\n"
        "int no_values(void) { return 0; }\n"
        "int* pointer_result(int& value) { return &value; }",
        "cpp",
    )
    params = {row["name"]: row["params"] for row in facts["functions"]}

    assert params == {
        "defaulted": 1,
        "variadic": 2,
        "no_values": 0,
        "pointer_result": 1,
    }


def test_static_and_nonpublic_members_are_file_private():
    facts = extract_facts(
        (
            "static int local_function() { return 0; }\n"
            "int global_function() { return 0; }\n"
            "class Secret { int hidden() { return 0; } "
            "public: int visible() { return 0; } };"
        ),
        "cpp",
    )
    privacy = {
        (row["owner"], row["name"]): row["file_private"] for row in facts["functions"]
    }

    assert privacy[(None, "local_function")] is True
    assert privacy[(None, "global_function")] is False
    assert privacy[("Secret", "hidden")] is True
    assert privacy[("Secret", "visible")] is False


def test_generated_header_is_recorded_without_excluding_file():
    facts = extract_facts(
        "// Code generated by tool; DO NOT EDIT.\nint build() { return 1; }", "cpp"
    )

    assert facts["markers"] == ["generated"]
    assert facts["excluded"] is None


def test_empty_constructor_is_exempt_but_initializing_constructor_is_not():
    facts = extract_facts(
        (
            "class Box { public: Box() {} Box(int value) { "
            "member = value; } int member; };"
        ),
        "cpp",
    )
    constructors = [row for row in facts["functions"] if row["name"] == "Box"]

    assert [row["exempt_role"] for row in constructors] == ["constructor", None]
