from varde_code.quality_pass.facts import extract_facts


def test_lifetime_and_type_generics_do_not_inflate_value_parameters():
    facts = extract_facts("fn borrow<'a, T>(value: &'a T) -> &'a T { value }", "rust")

    assert facts["functions"][0]["params"] == 1


def test_trait_impl_methods_are_tagged_and_question_mark_calls_are_measured():
    facts = extract_facts(
        "trait Load { fn load(&self) -> Result<(), E>; }\n"
        "impl Load for Store { fn load(&self) -> Result<(), E> { read()?; Ok(()) } }",
        "rust",
    )
    method = next(row for row in facts["functions"] if row["owner"] == "Store")

    assert method["name"] == "load"
    assert method["exempt_role"] == "override"
    assert method["cognitive"] == 0
    assert [site["name"] for site in facts["call_sites"]] == ["read", "Ok"]
    assert facts["call_coverage"] is None


def test_trait_impl_nested_helper_is_not_tagged_as_override():
    facts = extract_facts(
        "trait Render { fn render(&self); }\n"
        "impl Render for View { fn render(&self) { fn helper() {} helper(); } }",
        "rust",
    )
    helper = next(row for row in facts["functions"] if row["name"] == "helper")

    assert helper["exempt_role"] is None


def test_visibility_and_receiver_forms_are_handled():
    facts = extract_facts(
        "struct Boxed; impl Boxed { fn shared(&self) {} fn mutable(&mut self) {} "
        "fn owned(self: Box<Self>) {} fn new() -> Self { Boxed } }\n"
        "pub fn public() {} pub(crate) fn crate_local() {} fn private() {}",
        "rust",
    )
    rows = {row["name"]: row for row in facts["functions"]}

    assert [rows[name]["params"] for name in ("shared", "mutable", "owned")] == [
        0,
        0,
        0,
    ]
    assert rows["new"]["exempt_role"] == "constructor"
    assert rows["public"]["file_private"] is False
    assert rows["crate_local"]["file_private"] is False
    assert rows["private"]["file_private"] is True


def test_generated_header_is_recorded_without_excluding_file():
    facts = extract_facts(
        "// Code generated by tool; DO NOT EDIT.\npub fn build() {}", "rust"
    )

    assert facts["markers"] == ["generated"]
    assert facts["excluded"] is None


def test_macro_does_not_create_a_false_naming_issue_for_sibling_function():
    facts = extract_facts(
        'fn ordinary_operation() {}\nfn uses_macro() { println!("x"); }', "rust"
    )
    ordinary = next(
        row for row in facts["functions"] if row["name"] == "ordinary_operation"
    )

    assert ordinary["name_issues"] == []
