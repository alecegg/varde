from varde_code.quality_pass.facts import extract_facts


def test_lowercase_declarations_are_private_and_exported_names_are_public():
    facts = extract_facts(
        "package sample\nfunc hidden() {}\nfunc unused() {}\n"
        "func Public() { hidden() }\n",
        "go",
    )
    privacy = {row["name"]: row["file_private"] for row in facts["functions"]}

    assert privacy == {"hidden": True, "unused": False, "Public": False}


def test_error_check_flow_and_short_names_are_recorded():
    facts = extract_facts(
        "package sample\nfunc load(ctx Context) error {\n"
        " if err := read(ctx); err != nil { return err }\n return nil\n}\n",
        "go",
    )
    function = facts["functions"][0]

    assert function["params"] == 1
    assert function["name_issues"] == []
    assert facts["call_sites"][0]["name"] == "read"


def test_receiver_name_does_not_count_as_a_parameter():
    facts = extract_facts(
        "package sample\ntype Store struct{}\n"
        "func (s *Store) Get(ctx Context) error { return nil }\n",
        "go",
    )

    assert facts["functions"][0]["params"] == 1


def test_grouped_variadic_receiver_only_and_zero_parameters():
    facts = extract_facts(
        "package sample\nfunc grouped(a, b int, c string, rest ...byte) {}\n"
        "type Store struct{}\nfunc (s *Store) receiverOnly() {}\nfunc zero() {}\n",
        "go",
    )
    params = {row["name"]: row["params"] for row in facts["functions"]}

    assert params == {"grouped": 4, "receiverOnly": 0, "zero": 0}


def test_generated_header_is_recorded_without_excluding_file():
    facts = extract_facts(
        "// Code generated by tool; DO NOT EDIT.\npackage sample\nfunc Build() {}\n",
        "go",
    )

    assert facts["markers"] == ["generated"]
    assert facts["excluded"] is None
