"""Gate attacks G1-G6 (validation plan section 10), one test per attack and language.

Every cell runs ``scan_repo`` end to end against a pinned snapshot under the
test-only ``gate-test-cal`` calibration (mechanism proof, not validation). The
attacks are the specification: an expectation is never edited to pass.
"""

from __future__ import annotations

import subprocess
from pathlib import Path

import gate_sources_cs
import gate_sources_py
import gate_sources_ts
import pytest
from conftest import file_scores, score_repo, write_files
from gate_snapshots import LANGUAGES, SNAPSHOTS, Snapshot
from varde_code.extract.provider import CodeExtractionProvider
from varde_code.index.build import build
from varde_code.query import modes
from varde_code.query.params import QueryError
from varde_code.scan import core

FLOOR = "quality-file-floor"
CAP = "quality-function-cap"
MEAN = "quality-scope-mean"
UNSCORED = "quality-unscored-share"
OVERRIDES = ".varde-code/overrides.toml"


@pytest.fixture
def gate_root(
    monkeypatch: pytest.MonkeyPatch,
    tmp_path_factory: pytest.TempPathFactory,
    gate_calibration,
) -> Path:
    """An empty repo root on a neutral path, with scan using ``gate-test-cal``.

    A pytest ``test_*`` directory in the path would make every Python file a
    test path, so the root comes from ``mktemp`` instead of ``tmp_path``.
    """
    monkeypatch.setenv("VARDE_CONFIG_DIR", str(tmp_path_factory.mktemp("config")))
    monkeypatch.setattr(modes, "_INDEX_SERVICE", None)
    monkeypatch.setattr(core, "load_calibration", lambda path: gate_calibration)
    return tmp_path_factory.mktemp("gate") / "repo"


def git(root: Path, *args: str) -> None:
    subprocess.run(  # noqa: S603
        ["git", "-c", "user.name=t", "-c", "user.email=t@t", *args],  # noqa: S607
        cwd=root,
        check=True,
        capture_output=True,
    )


def commit_all(root: Path) -> None:
    git(root, "init", "-q")
    git(root, "add", ".")
    git(root, "commit", "-qm", "base", "--no-verify")


def restore(root: Path) -> None:
    git(root, "checkout", "-q", "--", ".")
    git(root, "clean", "-fdq")


def scan(root: Path, **options) -> dict:
    build(root, CodeExtractionProvider())
    return core.scan_repo({"repoRoot": str(root), "fullFindings": True, **options})


def findings(result: dict, rule_id: str) -> list[dict]:
    return [f for f in result["findings"] if f["rule_id"] == rule_id]


def flagged_files(result: dict, rule_id: str) -> set[str]:
    return {f["location"]["file"] for f in findings(result, rule_id)}


def diagnostics(result: dict, rule_id: str) -> list[dict]:
    return [d for d in result["diagnostics"] if d["rule_id"] == rule_id]


def override_text(**severities: str) -> str:
    return "".join(
        f'[rules.{rule_id}]\nseverity = "{severity}"\nreason = "gate attack"\n'
        for rule_id, severity in (
            (name.replace("_", "-"), value) for name, value in severities.items()
        )
    )


def with_function(snapshot: Snapshot, source: str, blocks: int) -> str:
    """Append one debt-heavy function of ``blocks`` branch blocks to ``source``."""
    if snapshot.language == "python":
        return source + "\n\n" + gate_sources_py._debt(blocks)
    if snapshot.language == "typescript":
        return source + "\n" + gate_sources_ts._debt(blocks)
    method = gate_sources_cs._debt_method(blocks)
    return source.rstrip()[:-1].rstrip() + "\n\n" + method + "}\n"


def clean_file_repeated(snapshot: Snapshot, times: int) -> str:
    """A large clean file: the clean snapshot file's functions repeated."""
    source = snapshot.files[snapshot.path("clean")]
    if snapshot.language != "csharp":
        return "\n".join([source] * times)
    body = source.rstrip()[:-1].rstrip()
    members = body.split("{", 1)[1].rstrip()
    return body + "\n" + "\n".join([members] * (times - 1)) + "\n}\n"


def tiny_function_pile(snapshot: Snapshot, count: int) -> str:
    """An overhead-exempt shape: many tiny forwarder-like functions in one file."""
    if snapshot.language == "csharp":
        method = (
            "    public static int Value{n}(int item)\n    {\n"
            "        return item + {n};\n    }\n\n"
        )
        body = "".join(method.replace("{n}", str(i)) for i in range(count))
        return "namespace Gate;\n\npublic static class Pile\n{\n" + body + "}\n"
    return "".join(
        snapshot.filler_tiny.replace("{n}", str(i)) + "\n" for i in range(count)
    )


# G1 and G2: marker and comment variants per language.
GENERATED_MARKERS = {
    "python": ("# @generated\n",),
    "typescript": ("// @generated\n", "/* @generated */\n"),
    "csharp": (
        "// @generated\n",
        "// <auto-generated>\n//   Generated by a tool.\n// </auto-generated>\n",
    ),
}
LONG_COMMENTS = {
    "python": ("# " + "x " * 3000 + "\n",),
    "typescript": ("// " + "x " * 3000 + "\n", "/* " + "x " * 3000 + "*/\n"),
    "csharp": ("// " + "x " * 3000 + "\n", "/// " + "x " * 3000 + "\n"),
}


@pytest.mark.parametrize("language", LANGUAGES)
def test_g1_generated_marker_alone_does_not_exclude_a_debt_file(language, gate_root):
    snapshot = SNAPSHOTS[language]
    debt = snapshot.path("debt")
    for marker in GENERATED_MARKERS[language]:
        files = {**snapshot.files, debt: marker + snapshot.files[debt]}
        write_files(gate_root, files)
        result = scan(gate_root)

        assert debt in flagged_files(result, FLOOR), marker
        assert debt in flagged_files(result, CAP), marker
        assert not findings(result, UNSCORED), marker
        assert result["gate"]["status"] == "fail", marker


@pytest.mark.parametrize("language", LANGUAGES)
def test_g2_long_comment_line_does_not_trigger_the_minified_exclusion(
    language, gate_root, gate_calibration
):
    snapshot = SNAPSHOTS[language]
    debt = snapshot.path("debt")
    clean = snapshot.path("clean")
    files = snapshot.files
    for comment in LONG_COMMENTS[language]:
        files = {
            **snapshot.files,
            debt: comment + snapshot.files[debt],
            clean: comment + snapshot.files[clean],
        }
        write_files(gate_root, files)
        result = scan(gate_root)

        assert debt in flagged_files(result, FLOOR), comment[:6]
        assert debt in flagged_files(result, CAP), comment[:6]
        assert not findings(result, UNSCORED), comment[:6]
    scored = file_scores(
        score_repo(gate_root.parent / "scored", files, gate_calibration)
    )
    assert scored[clean].excluded is None
    assert scored[clean].tokens > 0


# G3: configuration changed against the base ref.
def config_variants(snapshot: Snapshot) -> dict[str, dict[str, str]]:
    rule = (
        '[[rule]]\nid = "gate-extra-rule"\nkind = "pattern"\nseverity = "warning"\n'
        'name = "x"\ndescription = "x"\nmessage = "x"\nremediation = "x"\n'
        f'pattern = "eval($$$ARGS)"\nlanguages = ["{snapshot.language}"]\n'
    )
    return {
        "severity-override": {OVERRIDES: override_text(quality_scope_mean="off")},
        "rule-added": {".varde-code/rules/extra.toml": rule},
        "threshold-pin": {
            ".varde-code/quality-pin.toml": (
                'calibration_id = "gate-test-cal"\nformula = "vq1"\n'
            )
        },
    }


@pytest.mark.parametrize("language", LANGUAGES)
def test_g3_config_change_blocks_and_findings_use_the_base_config(
    language, tmp_path_factory, gate_root
):
    check_g3_fails_when_a_finding_blocks(SNAPSHOTS[language], gate_root)
    other = tmp_path_factory.mktemp("gate") / "repo"
    check_g3_unknown_without_a_blocking_finding(SNAPSHOTS[language], other)


def check_g3_fails_when_a_finding_blocks(snapshot: Snapshot, gate_root: Path) -> None:
    write_files(gate_root, snapshot.files)
    commit_all(gate_root)
    for name, changes in config_variants(snapshot).items():
        write_files(gate_root, changes)
        result = scan(gate_root, rulesRef="HEAD")

        changed = diagnostics(result, "config-changed")
        assert changed and all(d["blocking"] for d in changed), name
        assert findings(result, FLOOR), f"{name}: findings use the base config"
        assert result["gate"]["status"] == "fail", name
        assert "analysis-incomplete" in result["outcome_reasons"], name
        restore(gate_root)


def check_g3_unknown_without_a_blocking_finding(
    snapshot: Snapshot, gate_root: Path
) -> None:
    base = override_text(quality_file_floor="off", quality_function_cap="off")
    write_files(gate_root, {**snapshot.files, OVERRIDES: base})
    commit_all(gate_root)
    variants = config_variants(snapshot)
    variants["severity-override"] = {
        OVERRIDES: base + override_text(quality_scope_mean="off")
    }
    for name, changes in variants.items():
        write_files(gate_root, changes)
        result = scan(gate_root, rulesRef="HEAD")

        changed = diagnostics(result, "config-changed")
        assert changed and all(d["blocking"] for d in changed), name
        assert result["gate"]["blocking_findings"] == 0, name
        assert result["gate"]["status"] == "unknown", name
        assert result["outcome_reasons"] == ["analysis-incomplete"], name
        restore(gate_root)


# G4: a file below Y with the floor rule at error, warning and off.
@pytest.mark.parametrize("language", LANGUAGES)
def test_g4_floor_severity_with_threshold_and_gate_rules(language, gate_root):
    snapshot = SNAPSHOTS[language]
    debt = snapshot.path("debt")
    write_files(gate_root, snapshot.files)
    cap_off = override_text(quality_function_cap="off")
    expected = {"error": "fail", "warning": "pass", "off": "pass"}

    for severity, status in expected.items():
        write_files(
            gate_root, {OVERRIDES: cap_off + override_text(quality_file_floor=severity)}
        )
        result = scan(gate_root)

        flagged = findings(result, FLOOR)
        assert result["gate"]["status"] == status, severity
        if severity == "off":
            assert not flagged
        else:
            assert {f["location"]["file"] for f in flagged} == {debt}
            assert {f["severity"] for f in flagged} == {severity}

    for severity in ("error", "warning"):
        write_files(
            gate_root, {OVERRIDES: cap_off + override_text(quality_file_floor=severity)}
        )
        result = scan(gate_root, gateRules=[FLOOR])
        assert result["gate"]["status"] == "fail", severity

    write_files(
        gate_root, {OVERRIDES: cap_off + override_text(quality_file_floor="off")}
    )
    with pytest.raises(QueryError) as error:
        scan(gate_root, gateRules=[FLOOR])
    assert error.value.code == "invalid_input"


# G5: a file above Y with one function above the cap.
@pytest.mark.parametrize("language", LANGUAGES)
def test_g5_function_cap_is_reported_although_the_file_passes(
    language, gate_root, gate_calibration
):
    snapshot = SNAPSHOTS[language]
    path = f"gate/big.{snapshot.ext}"
    source = with_function(snapshot, clean_file_repeated(snapshot, 14), 7)
    write_files(gate_root, {path: source})
    result = scan(gate_root)

    y = gate_calibration.languages[language].parameters["Y"]
    cap = gate_calibration.languages[language].parameters["cap"]
    scored = file_scores(
        score_repo(gate_root.parent / "scored", {path: source}, gate_calibration)
    )[path]
    assert scored.gate_score > y
    assert not findings(result, FLOOR)
    caps = findings(result, CAP)
    assert {f["location"]["file"] for f in caps} == {path}
    assert len(caps) == 1
    assert caps[0]["evidence"]["debt"] > cap
    assert result["gate"]["status"] == "fail"


# G6: a bad function moved into an overhead-exempt file.
@pytest.mark.parametrize("language", LANGUAGES)
def test_g6_bad_function_in_an_exempt_file_keeps_cap_and_weighs_in_the_mean(
    language, gate_root, gate_calibration
):
    snapshot = SNAPSHOTS[language]
    debt = snapshot.path("debt")
    pile = f"gate/pile.{snapshot.ext}"
    files = {
        **snapshot.files,
        debt: snapshot.filler_tiny.replace("{n}", "0"),
        pile: with_function(snapshot, tiny_function_pile(snapshot, 60), 7),
    }
    write_files(gate_root, files)
    result = scan(gate_root)

    assert pile not in flagged_files(result, FLOOR)
    assert pile in flagged_files(result, CAP)
    assert result["gate"]["status"] == "fail"
    scope = score_repo(gate_root.parent / "scored", files, gate_calibration)
    exempt = file_scores(scope)[pile]
    assert exempt.exempt_from_floor
    assert scope.tokens == sum(f.tokens for f in scope.files)
    assert scope.tokens > exempt.tokens > 0
    assert scope.debt == sum(f.debt for f in scope.files)
    assert exempt.debt > 0
