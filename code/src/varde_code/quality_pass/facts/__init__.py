@cache
def quality_extractor_version() -> str:
    """Hash fact dependencies and parser package versions for cache keys."""
    package = Path(__file__).parents[1]
    root = package.parent
    dependency_files = [root / "complexity.py", root / "parse.py", root / "model.py"]
    dependency_files.extend(
        path for path in (root / "extract").rglob("*") if path.is_file()
    )
    dependency_files.extend(path for path in package.rglob("*") if path.is_file())
    versions = {
        distribution: importlib.metadata.version(distribution)
        for distribution in ("tree-sitter", "tree-sitter-language-pack")
    }
    return _version_digest(dependency_files, versions, root)


def _version_digest(paths: list[Path], versions: dict[str, str], root: Path) -> str:
    digest = hashlib.blake2b(digest_size=32)
    for path in sorted(set(paths)):
        if path.suffix == ".pyc" or "__pycache__" in path.parts:
            continue
        digest.update(path.relative_to(root).as_posix().encode())
        digest.update(path.read_bytes())
    for name, version in sorted(versions.items()):
        digest.update(name.encode())
        digest.update(version.encode())
    return f"blake2b-{digest.hexdigest()}"


def extract_facts(source: str | bytes, language: str, path: str = "") -> dict:
    """Extract one deterministic facts-2 record from source text or bytes.

    The second parse is deliberate: ``extract_file`` must remain unmodified and
    does not expose its parsed tree. This pass needs that tree for token and call
    walks, so its cold cost includes one additional parse per file.
    """
    raw = source.encode("utf-8") if isinstance(source, str) else source
    text = raw.decode("utf-8-sig", errors="replace")
    extracted = extract_file(path, text, language)
    parsed = parse_source_for_path(language, path, text)
    root = parsed.root
    content_hash = (
        f"blake2b-{hashlib.blake2b(parsed.source, digest_size=32).hexdigest()}"
    )
    plugin = language_module(parsed.lang)
    function_nodes = _function_nodes(root)
    function_nodes.extend(_plugin_function_nodes(root, plugin))
    _add_named_arrow_entities(extracted.entities, function_nodes)
    functions = [
        entity for entity in extracted.entities if entity.kind == EntityKind.FUNCTION
    ]
    records, function_diagnostics = _function_records(
        functions, function_nodes, parsed.source, parsed.lang, plugin
    )
    _apply_overload_pairs(
        records,
        _plugin_value(
            plugin, "overload_pairs", records, root, parsed.source, default=[]
        ),
    )
    package_prefix = _package_prefix(parsed.source, parsed.lang)
    types = _type_records(root, parsed.source, path, parsed.lang, package_prefix)
    declared_type_names = {item["name"] for item in types}
    complexities = function_complexities(
        [replace(entity, is_test=False) for entity in extracted.entities]
    )
    complexity_by_key = {
        (item.name, item.owner_type, item.span.start_byte): item.cognitive
        for item in complexities
    }
    for record in records:
        record["cognitive"] = complexity_by_key.get(
            (record["name"], record["owner"], _record_start(record, functions)), 0
        )
        record["qualifier"] = _function_qualifier(
            record["_node"], parsed.source, parsed.lang, package_prefix
        )
        if parsed.lang in {"cpp", "c++"}:
            prefix = _cpp_out_of_line_prefix(record["_node"], parsed.source)
            if prefix:
                record["qualifier"] = prefix
                owner = prefix.split(".")[-1]
                record["owner"] = owner if owner in declared_type_names else None
        record["id"] = f"{path}::{record['id']}"
        if record["overload_pair"] is not None:
            record["overload_pair"] = f"{path}::{record['overload_pair']}"
    calls = _call_sites(root, parsed.source, records, plugin)
    explicit_exports = _plugin_value(
        plugin, "exported_names", root, parsed.source, default=set()
    )
    references = Counter(
        symbol.name for symbol in extracted.symbols if symbol.kind.name == "REFERENCE"
    )
    declarations = Counter(record["name"] for record in records)
    for name, count in declarations.items():
        references[name] = max(0, references[name] - count)
    call_references = Counter(
        call["name"] for call in calls if call.get("kind") != "new"
    )
    for name, count in call_references.items():
        references[name] = max(references[name], count)
    for record in records:
        is_exported = (
            record["name"] in explicit_exports
            or (record["owner"], record["name"]) in explicit_exports
        )
        default_private = references[record["name"]] > 0 and not is_exported
        private = _plugin_value(
            plugin,
            "file_private",
            record,
            root,
            parsed.source,
            references,
            default=default_private,
        )
        record["file_private"] = private
        issues = _name_issues(record["name"])
        issues.extend(_plugin_value(plugin, "convention_issues", record, default=[]))
        record["name_issues"] = list(
            _plugin_value(plugin, "filter_name_issues", record, issues, default=issues)
        )
    markers = sorted(
        set(_markers(root, parsed.source))
        | set(_plugin_value(plugin, "markers", root, parsed.source, path, default=[]))
    )
    code_tokens = _count_tokens(root, parsed.source)[0]
    minified = _is_minified(root, parsed.source)
    literal_ids = [record["id"] for record in records if record["literal_ratio"] >= 0.9]
    for record in records:
        record.pop("_start_byte", None)
        record.pop("_end_byte", None)
        record.pop("_node", None)
        record.pop("literal_ratio", None)
    return {
        "contract": "facts-2",
        "path": path,
        "language": parsed.lang,
        "content_hash": content_hash,
        "tokens": code_tokens,
        "excluded": "minified" if minified else None,
        "markers": markers,
        "unmeasured_regions": _normalize_regions(
            _plugin_value(plugin, "unmeasured_regions", root, parsed.source, default=[])
        ),
        "comment_parity": {
            "tokens": code_tokens,
            "comment_tokens": _count_comment_tokens(root, parsed.source),
        },
        "import_fan_out": None,
        "functions": records,
        "types": types,
        "data_functions": literal_ids,
        "call_sites": calls,
        "call_coverage": None,
        "unresolved_share": None,
        "structure_confidence": None,
        "diagnostics": function_diagnostics
        + (["parse contains errors"] if parsed.has_error() else []),
    }


def normalize_record(record: dict) -> dict:
    """Return a facts-2 record, filling optional fields older records may miss.

    Accepts producer output of contract ``facts-1`` or ``facts-2`` and rejects
    any other version string. The returned copy always declares ``facts-2``;
    ``markers``, ``comment_parity``, ``unmeasured_regions`` and per-function
    ``overload_pair`` default to their neutral values when absent.
    """
    contract = record.get("contract")
    if contract not in {"facts-1", "facts-2"}:
        raise ValueError(f"unknown facts contract: {contract!r}")
    normalized = dict(record)
    normalized["contract"] = "facts-2"
    normalized.setdefault("markers", [])
    normalized.setdefault(
        "comment_parity",
        {"tokens": record.get("tokens", 0), "comment_tokens": 0},
    )
    normalized.setdefault("unmeasured_regions", [])
    normalized.setdefault("types", [])
    if "functions" in record:
        normalized["functions"] = [
            {
                "qualifier": "",
                **function,
                "overload_pair": function.get("overload_pair"),
            }
            for function in record["functions"]
        ]
    return normalized


def _plugin_value(plugin: object | None, hook: str, *args, default):
    function = getattr(plugin, hook, None) if plugin is not None else None
    if function is None:
        return default
    value = function(*args)
    return default if value is None else value


def _apply_overload_pairs(records: list[dict], pairs: list) -> None:
    """Tag each record of a plugin-declared overload pair with its sibling id."""
    by_id = {record["id"]: record for record in records}
    for pair in pairs:
        first, second = pair
        left = by_id.get(first)
        right = by_id.get(second)
        if left is None or right is None or left is right:
            continue
        left["overload_pair"] = right["id"]
        right["overload_pair"] = left["id"]


def _normalize_regions(regions: list) -> list[dict]:
    """Return plugin-declared unmeasured spans sorted and deduplicated."""
    unique = {
        (region["kind"], region["start_line"], region["end_line"]) for region in regions
    }
    return [
        {"kind": kind, "start_line": start_line, "end_line": end_line}
        for kind, start_line, end_line in sorted(
            unique, key=lambda item: (item[1], item[2], item[0])
        )
    ]


def _add_named_arrow_entities(entities: list, nodes: list) -> None:
    present = {
        (entity.name, entity.span.start_byte)
        for entity in entities
        if entity.kind == EntityKind.FUNCTION
    }
    for node in nodes:
        if node.type not in {"arrow_function", "function_expression"}:
            continue
        parent = node.parent
        name_node = parent.child_by_field_name("name") if parent is not None else None
        if name_node is None:
            continue
        name = name_node.text.decode(errors="replace")
        if (name, node.start_byte) in present:
            continue
        entities.append(
            Entity(
                kind=EntityKind.FUNCTION,
                name=name,
                file_id=0,
                span=span_of(node),
            )
        )


def _record_start(record: dict, entities: list) -> int:
    return next(
        (
            e.span.start_byte
            for e in entities
            if e.name == record["name"]
            and e.span.start_line == record["line"]
            and e.owner_type == record["owner"]
        ),
        -1,
    )


def _function_nodes(root: Node) -> list[Node]:
    nodes = []
    stack = [root]
    while stack:
        node = stack.pop()
        if node.type in {
            "function_definition",
            "function_declaration",
            "method_definition",
            "function_item",
            "arrow_function",
            "function_expression",
            "method_declaration",
            "func_literal",
            "local_function_statement",
        }:
            nodes.append(node)
        stack.extend(reversed(node.named_children))
    return nodes


def _plugin_function_nodes(root: Node, plugin: object | None) -> list[Node]:
    """Find extra callable syntax kinds declared by a language plugin."""
    node_types = _plugin_value(plugin, "function_node_types", default=set())
    if not node_types:
        return []
    nodes = []
    stack = [root]
    while stack:
        node = stack.pop()
        if node.type in node_types:
            nodes.append(node)
        stack.extend(reversed(node.named_children))
    return nodes


def _function_records(
    entities: list, nodes: list, source: bytes, language: str, plugin: object | None
) -> tuple[list[dict], list[str]]:
    rows = []
    diagnostics = []
    ordinals: Counter[str] = Counter()
    ordered = sorted(entities, key=lambda entity: (entity.span.start_byte, entity.name))
    for entity in ordered:
        node = _matching_function_node(entity, nodes, source, plugin)
        if _is_bodyless_member(node, language):
            continue
        body = (
            _plugin_value(plugin, "function_body", node, default=None)
            if node is not None
            else None
        )
        if body is None:
            body = _body(node) if node is not None else None
        token_count = _count_tokens(node, source)[0] if node is not None else 0
        body_node = body if body is not None else node
        literal_ratio = _data_literal_ratio(body_node, source) if body_node else 0.0
        if node is None:
            diagnostics.append(
                f"function node not found: {entity.name}:{entity.span.start_line}"
            )
        qualified = (
            f"{entity.owner_type}.{entity.name}" if entity.owner_type else entity.name
        )
        ordinals[qualified] += 1
        params = _parameter_count(node, plugin)
        role = _verified_role(
            {
                "entity": entity,
                "node": node,
                "body": body,
                "source": source,
                "tokens": token_count,
                "params": params,
                "language": language,
            },
            plugin,
        )
        rows.append(
            {
                "id": f"{qualified}#{ordinals[qualified]}",
                "name": entity.name,
                "owner": entity.owner_type,
                "line": entity.span.start_line,
                "end_line": entity.span.end_line,
                "tokens": token_count,
                "params": params,
                "cognitive": 0,
                "exempt_role": role,
                "file_private": False,
                "overload_pair": None,
                "callers_in_module": None,
                "fragment_scope": None,
                "module": None,
                "depth": None,
                "fan_out": None,
                "tree_size": None,
                "cross_module_depth": None,
                "opaque_calls": None,
                "depth_capped": None,
                "name_issues": [],
                "literal_ratio": literal_ratio,
                "_start_byte": entity.span.start_byte,
                "_end_byte": entity.span.end_byte,
                "_node": node,
            }
        )
    return rows, diagnostics


def _matching_function_node(
    entity: Entity, nodes: list[Node], source: bytes, plugin: object | None = None
) -> Node | None:
    overlapping = []
    for node in nodes:
        if (
            entity.span.end_byte < node.start_byte
            or entity.span.start_byte > node.end_byte
        ):
            continue
        name_node = node.child_by_field_name("name")
        node_name = _plugin_value(
            plugin, "function_node_name", node, source, default=None
        )
        if node_name is None and name_node is not None:
            node_name = source[name_node.start_byte : name_node.end_byte].decode(
                errors="replace"
            )
        if node_name is not None and node_name != entity.name:
            continue
        overlapping.append(node)
    if not overlapping:
        return None
    return min(
        overlapping,
        key=lambda node: (
            0 if node.start_byte == entity.span.start_byte else 1,
            abs(node.start_byte - entity.span.start_byte),
            node.end_byte - node.start_byte,
        ),
    )


def _is_bodyless_member(node: Node | None, language: str) -> bool:
    """A C# interface, abstract, extern or partial member has no body to score."""
    return (
        language == "csharp"
        and node is not None
        and node.type == "method_declaration"
        and node.child_by_field_name("body") is None
    )


def _body(node: Node | None) -> Node | None:
    if node is None:
        return None
    body_types = {
        "block",
        "body",
        "statement_block",
        "function_body",
        "declaration_list",
    }
    return next(
        (child for child in node.named_children if child.type in body_types), None
    )


def _parameter_count(node: Node | None, plugin: object | None = None) -> int:
    """Count declared parameters, including Python self/cls, excluding Go receivers."""
    if node is None:
        return 0
    override = _plugin_value(plugin, "parameter_count", node, default=None)
    if override is not None:
        return override
    params = node.child_by_field_name("parameters")
    if params is None:
        params = node.child_by_field_name("parameter")
    if params is None:
        params = next(
            (
                child
                for child in node.named_children
                if child.type in {"formal_parameters", "parameters", "parameter_list"}
            ),
            None,
        )
    if params is None:
        return 0
    if params.type == "identifier":
        return 1
    return sum(1 for child in params.named_children if child.type not in _COMMENTS)


def _verified_role(context: dict, plugin: object | None) -> str | None:
    entity = context["entity"]
    node = context["node"]
    body = context["body"]
    source = context["source"]
    if entity.is_test:
        return "test"
    if node is None:
        return None
    role = _plugin_value(
        plugin,
        "verified_role",
        _record_for_entity(entity),
        node,
        body,
        source,
        default=None,
    )
    if role in {"constructor", "override", "handler", "fixture", "accessor", "test"}:
        return role
    constructor_role = _constructor_role(context)
    if constructor_role is not None:
        return constructor_role
    if _plugin_value(
        plugin,
        "suppress_accessor_fallback",
        _record_for_entity(entity),
        node,
        body,
        source,
        default=False,
    ):
        return None
    return _accessor_role(
        body, source, context["tokens"], _parameter_names(node, source)
    )


def _record_for_entity(entity: Entity) -> dict:
    return {
        "name": entity.name,
        "owner": entity.owner_type,
        "line": entity.span.start_line,
    }


def _constructor_role(context: dict) -> str | None:
    entity = context["entity"]
    node = context["node"]
    body = context["body"]
    source = context["source"]
    tokens = context["tokens"]
    language = context["language"]
    params = context["params"]
    names = {
        "python": "__init__",
        "javascript": "constructor",
        "typescript": "constructor",
        "tsx": "constructor",
        "java": entity.owner_type,
        "csharp": entity.owner_type,
    }
    if (
        not entity.owner_type
        or entity.name != names.get(language)
        or body is None
        or tokens > 40
    ):
        return None
    statements = [
        statement
        for statement in body.named_children
        if statement.type not in _COMMENTS
    ]
    if not statements:
        return None
    parameter_names = _parameter_names(node, source)
    if not parameter_names or params > 8:
        return None
    for iter_statement in statements:
        statement = _unwrap_expression(iter_statement)
        if statement.type in {"pass_statement", "empty_statement"}:
            continue
        if "assignment" not in statement.type:
            return None
        left = statement.child_by_field_name("left")
        right = statement.child_by_field_name("right")
        if left is None or right is None or right.type != "identifier":
            return None
        right_name = source[right.start_byte : right.end_byte].decode(errors="replace")
        left_text = source[left.start_byte : left.end_byte].decode(errors="replace")
        if right_name not in parameter_names or not re.match(
            r"(?:self|this)\.", left_text
        ):
            return None
    return "constructor"


def _accessor_role(
    body: Node | None, source: bytes, tokens: int, parameter_names: set[str]
) -> str | None:
    if body is None or tokens > 40:
        return None
    statements = [child for child in body.named_children if child.type not in _COMMENTS]
    if len(statements) != 1:
        return None
    statement = _unwrap_expression(statements[0])
    if statement.type in {"return_statement", "return_expression"}:
        values = [
            child for child in statement.named_children if child.type not in _COMMENTS
        ]
        return (
            "accessor"
            if len(values) == 1
            and values[0].type
            in {
                "identifier",
                "attribute",
                "member_expression",
                "field_expression",
                "scoped_identifier",
            }
            else None
        )
    if "assignment" in statement.type:
        left = statement.child_by_field_name("left")
        right = statement.child_by_field_name("right")
        if (
            left is not None
            and right is not None
            and left.type in {"identifier", "attribute", "member_expression"}
            and right.type == "identifier"
        ):
            right_name = source[right.start_byte : right.end_byte].decode(
                errors="replace"
            )
            return "accessor" if right_name in parameter_names else None
    return None


def _unwrap_expression(statement: Node) -> Node:
    if statement.type == "expression_statement" and len(statement.named_children) == 1:
        return statement.named_children[0]
    return statement


def _parameter_names(node: Node, source: bytes) -> set[str]:
    params = node.child_by_field_name("parameters") or node.child_by_field_name(
        "parameter"
    )
    if params is None:
        params = next(
            (
                child
                for child in node.named_children
                if child.type in {"formal_parameters", "parameters", "parameter_list"}
            ),
            None,
        )
    if params is None:
        return set()
    candidates = params.named_children if params.type != "identifier" else [params]
    names = set()
    for parameter in candidates:
        if parameter.type == "identifier":
            names.add(
                source[parameter.start_byte : parameter.end_byte].decode(
                    errors="replace"
                )
            )
            continue
        name_node = parameter.child_by_field_name("name")
        if name_node is not None and name_node.type == "identifier":
            names.add(
                source[name_node.start_byte : name_node.end_byte].decode(
                    errors="replace"
                )
            )
        elif parameter.type in {"identifier", "simple_parameter"}:
            names.update(
                source[child.start_byte : child.end_byte].decode(errors="replace")
                for child in parameter.named_children
                if child.type == "identifier"
            )
    return names


def _walk(node: Node):
    stack = [node]
    while stack:
        current = stack.pop()
        yield current
        stack.extend(reversed(current.children))


def _count_tokens(node: Node, source: bytes) -> tuple[int, int]:
    count = literals = 0
    stack = [node]
    while stack:
        leaf = stack.pop()
        if leaf.type in _COMMENTS:
            continue
        weight = _token_literal_weight(leaf, source)
        if weight is not None:
            literals += weight
            count += weight
            continue
        if leaf.children:
            stack.extend(reversed(leaf.children))
            continue
        text = source[leaf.start_byte : leaf.end_byte]
        if leaf.type in _LITERALS:
            literals += 1
            count += 1
        elif text.strip():
            count += 1
    return count, literals


def _is_string_literal(node: Node, source: bytes) -> bool:
    if node.type not in _STRING_LITERALS:
        return False
    if node.type != "string":
        return True
    text = source[node.start_byte : node.end_byte].lstrip()
    return re.match(rb"^[rubfRUBF]*['\"]", text) is not None


def _token_literal_weight(node: Node, source: bytes) -> int | None:
    if node.type == "char_literal":
        return 1
    if _is_string_literal(node, source):
        return _string_weight(node, source)
    return None


def _string_weight(node: Node, source: bytes) -> int:
    if node.type == "regex":
        return 1
    text = source[node.start_byte : node.end_byte].decode(errors="replace")
    match = re.match(r"^[rubfRUBF$@]*('''|\"\"\"|'|\"|`)", text)
    if match:
        quote = match.group(1)
        end = -len(quote) if text.endswith(quote) else None
        text = text[match.end() : end]
    return min(32, (len(text) + 7) // 8)


def _data_literal_ratio(node: Node, source: bytes) -> float:
    """Measure literal content while excluding list and map delimiters."""
    if node is None:
        return 0.0
    literals = total = 0
    wrappers = {"return", "yield", "yield_from"}
    punctuation = {",", ";", "[", "]", "(", ")", "{", "}", ":"}
    stack = [node]
    while stack:
        item = stack.pop()
        if item.type in _COMMENTS:
            continue
        weight = _token_literal_weight(item, source)
        if weight is not None:
            total += weight
            literals += weight
            continue
        if item.children:
            stack.extend(reversed(item.children))
            continue
        if item.type in punctuation or item.type in wrappers:
            continue
        token_count, literal_count = _count_tokens(item, source)
        total += token_count
        literals += literal_count
    return literals / total if total else 0.0


def _count_comment_tokens(node: Node, source: bytes) -> int:
    count = 0
    for item in _walk(node):
        if item.type in _COMMENTS and not item.children:
            count += len(source[item.start_byte : item.end_byte].split())
    return count


def _markers(root: Node, source: bytes, work: dict | None = None) -> list[str]:
    """Find marker notices in header comments with one ordered tree walk."""
    found = set()
    header_end = _header_end(root, len(source))
    line_starts = [0]
    line_starts.extend(index + 1 for index, byte in enumerate(source) if byte == 10)
    header_comment_lines = 0
    for node in _walk(root):
        if node.type not in _COMMENTS:
            continue
        text = node.text
        if text is None:
            continue
        lines = text.decode(errors="replace").splitlines() or [""]
        in_header = node.start_byte < header_end
        for line_index, line in enumerate(lines):
            if work is not None:
                work["comment_lines"] = work.get("comment_lines", 0) + 1
            text = _comment_line_text(line)
            marker = _marker_kind(text)
            if marker is None:
                continue
            header_line = (
                in_header
                and header_comment_lines + line_index < _MAX_HEADER_COMMENT_LINES
            )
            standalone = _is_standalone_marker_line(
                text, marker, node, line_index, source, line_starts
            )
            if header_line or standalone:
                found.add(marker)
        if in_header:
            header_comment_lines += len(lines)
    return sorted(found)


def _header_end(root: Node, source_length: int) -> int:
    """End the initial comments/imports/directives header before source code."""
    for node in root.named_children:
        if node.type in _COMMENTS or node.type in _HEADER_PREAMBLE_TYPES:
            continue
        if node.type == "string" or _is_string_directive(node):
            continue
        return node.start_byte
    return source_length


def _is_string_directive(node: Node) -> bool:
    return (
        node.type == "expression_statement"
        and len(node.named_children) == 1
        and node.named_children[0].type in _STRING_LITERALS
    )


def _comment_line_text(line: str) -> str:
    text = line.strip()
    prefix = True
    while prefix:
        prefix = False
        for marker in ("//", "#", "/*", "*", "<!--", "/"):
            if text.startswith(marker):
                text = text[len(marker) :].strip()
                prefix = True
                break
    for suffix in ("*/", "-->"):
        if text.endswith(suffix):
            text = text[: -len(suffix)].strip()
            break
    return text


def _marker_kind(text: str) -> str | None:
    if not text or _MANUAL_SOURCE.search(text):
        return None
    for marker, pattern in _MARKERS:
        if not pattern.search(text):
            continue
        if marker == "generated" and _is_generated_notice(text):
            return marker
        if marker == "vendored" and _is_vendored_notice(text):
            return marker
    return None


def _is_generated_notice(text: str) -> bool:
    lower = text.strip().lower()
    if lower.startswith(("@generated", "<auto-generated", "do not edit")):
        return True
    if re.match(r"^auto(?:matically)?[- ]?generated\b", lower):
        return True
    if re.match(
        r"^(?:this|the)\s+file\s+(?:is|was)\s+"
        r"(?:auto(?:matically)?[- ]?)?generated\b",
        lower,
    ):
        return True
    if re.match(
        r"^(?:a|an)\s+\w+(?:[\w.-]*\s+\w+){0,5}\s+generated\s+(?:by|from)\b", lower
    ):
        return True
    generated = re.match(r"^(?:code\s+)?generated\b(.*)$", lower)
    if generated is None:
        return False
    remainder = generated.group(1).strip()
    return (
        not remainder
        or remainder.startswith(("by ", "from ", "file", "code", "source", "output"))
        or remainder[0] in ".!:"
    )


def _is_vendored_notice(text: str) -> bool:
    lower = text.strip().lower()
    if lower.startswith("third-party source") or lower == "vendored":
        return True
    return lower.startswith(("vendored from ", "vendored source"))


def _is_standalone_marker_line(
    text: str,
    marker: str,
    node: Node,
    line_index: int,
    source: bytes,
    line_starts: list[int],
) -> bool:
    normalized = re.sub(r"[\s.!:;,]+$", "", text.strip()).lower()
    if marker == "generated":
        is_marker_line = (
            normalized
            in {
                "generated",
                "code generated",
                "generated file",
                "code generated file",
                "auto-generated",
                "auto generated",
                "automatically generated",
                "autogenerated",
                "@generated",
                "do not edit",
            }
            or normalized.startswith("<auto-generated")
            and normalized.endswith(">")
        )
    else:
        is_marker_line = normalized in {
            "vendored",
            "vendored source",
            "third-party source",
        }
    if not is_marker_line:
        return False
    row = node.start_point[0] + line_index
    line_start = line_starts[row]
    line_end = line_starts[row + 1] if row + 1 < len(line_starts) else len(source)
    if row == node.start_point[0] and source[line_start : node.start_byte].strip():
        return False
    return not (row == node.end_point[0] and source[node.end_byte : line_end].strip())


def _is_minified(root: Node, source: bytes) -> bool:
    """Require a 50-token median on 3+ code lines or 500 tokens on one line."""
    line_counts: Counter[int] = Counter()
    for node in _walk(root):
        if node.children or node.type in _COMMENTS or _is_string_literal(node, source):
            continue
        line_counts[node.start_point[0]] += 1
    if len(line_counts) == 1:
        return next(iter(line_counts.values())) >= 500
    if len(line_counts) < 3:
        return False
    sorted_counts = sorted(line_counts.values())
    median = sorted_counts[len(sorted_counts) // 2]
    return median >= 50


def _call_sites(
    root: Node, source: bytes, functions: list[dict], plugin: object | None
) -> list[dict]:
    calls = []
    call_nodes = [node for node in _walk(root) if node.type in _CALLS]
    enclosing_functions = _enclosing_functions(functions, call_nodes)
    for node, caller in zip(call_nodes, enclosing_functions, strict=True):
        if node.type in _CREATIONS:
            created = _created_type_text(node, source, plugin)
            if created is None:
                continue
            parts = re.split(r"\s*(?:\.|::)\s*", created)
            type_name = parts[-1].split("<", 1)[0]
            args = node.child_by_field_name("arguments") or next(
                (c for c in node.named_children if c.type == "argument_list"), None
            )
            calls.append(
                {
                    "caller": caller["id"] if caller else None,
                    "name": type_name,
                    "receiver": None,
                    "receiver_text": ".".join(parts[:-1]) or None,
                    "arity": _argument_count(args),
                    "line": node.start_point[0] + 1,
                    "kind": "new",
                }
            )
            continue
        function_node = node.child_by_field_name("function")
        name_node = function_node or node.child_by_field_name("name")
        args = node.child_by_field_name("arguments")
        if name_node is None:
            continue
        name, receiver, receiver_text = _call_name_and_receiver(
            node, name_node, function_node, source
        )
        plugin_call = _plugin_value(plugin, "call_site", node, source, default={})
        name = plugin_call.get("name", name)
        receiver = plugin_call.get("receiver", receiver)
        receiver_text = plugin_call.get("receiver_text", receiver_text)
        arity = plugin_call.get("arity", _argument_count(args))
        calls.append(
            {
                "caller": caller["id"] if caller else None,
                "name": name,
                "receiver": receiver,
                "receiver_text": receiver_text,
                "arity": arity,
                "line": node.start_point[0] + 1,
            }
        )
    return calls


_CREATIONS = {
    "object_creation_expression",
    "new_expression",
    "implicit_object_creation_expression",
}


def _created_type_text(node: Node, source: bytes, plugin: object | None) -> str | None:
    """Return the constructed type's text, or None when no type is named."""
    if node.type == "implicit_object_creation_expression":
        return _plugin_value(
            plugin, "implicit_creation_type", node, source, default=None
        )
    type_node = node.child_by_field_name("type") or node.child_by_field_name(
        "constructor"
    )
    if type_node is None:
        return None
    if node.type == "new_expression":
        type_text = _node_text(type_node, source).strip()
        if not re.fullmatch(r"[\w:]+(?:\s*(?:\.|::)\s*[\w:]+)*", type_text):
            return None
    return _node_text(type_node, source)


def _enclosing_functions(functions: list[dict], call_nodes: list) -> list[dict | None]:
    """Find the narrowest enclosing function for each call node in O((F+C) log F)."""
    intervals = sorted(
        (
            function["_start_byte"],
            _function_end(function),
            index,
            function,
        )
        for index, function in enumerate(functions)
    )
    queries = sorted(enumerate(call_nodes), key=lambda item: item[1].start_byte)
    active = [False] * len(functions)
    by_span = []
    by_end = []
    next_interval = 0
    result: list[dict | None] = [None] * len(call_nodes)
    for call_index, node in queries:
        position = node.start_byte
        while (
            next_interval < len(intervals) and intervals[next_interval][0] <= position
        ):
            start, end, function_index, function = intervals[next_interval]
            active[function_index] = True
            heapq.heappush(
                by_span,
                (end - start, function_index, end, function),
            )
            heapq.heappush(by_end, (end, function_index))
            next_interval += 1
        while by_end and by_end[0][0] < position:
            _, function_index = heapq.heappop(by_end)
            active[function_index] = False
        while by_span and not active[by_span[0][1]]:
            heapq.heappop(by_span)
        if by_span:
            result[call_index] = by_span[0][3]
    return result


_TYPE_NODES = {
    "class_declaration": "class",
    "abstract_class_declaration": "class",
    "type_alias_declaration": "type",
    "class_definition": "class",
    "class_specifier": "class",
    "struct_specifier": "struct",
    "struct_declaration": "struct",
    "struct_item": "struct",
    "interface_declaration": "interface",
    "trait_item": "trait",
    "enum_declaration": "enum",
    "enum_item": "enum",
    "enum_specifier": "enum",
    "record_declaration": "record",
    "type_declaration": "type",
    "type_spec": "type",
    "type_alias": "type",
    "annotation_type_declaration": "interface",
}


def _type_records(
    root: Node, source: bytes, path: str, language: str, package_prefix: list[str]
) -> list[dict]:
    records = []
    counts: Counter[str] = Counter()
    for node in _walk(root):
        kind = _TYPE_NODES.get(node.type)
        name_node = node.child_by_field_name("name")
        if name_node is None and kind is not None:
            name_node = next(
                (
                    child
                    for child in node.named_children
                    if child.type in {"type_identifier", "identifier", "name"}
                ),
                None,
            )
        if kind is None or name_node is None:
            continue
        if (
            node.type in {"class_specifier", "struct_specifier", "enum_specifier"}
            and node.child_by_field_name("body") is None
        ):
            continue
        name = _node_text(name_node, source).split("<", 1)[0]
        if node.type == "type_spec":
            declared = next(
                (
                    child
                    for child in node.named_children
                    if child.type in {"struct_type", "interface_type"}
                ),
                None,
            )
            kind = (
                "struct"
                if declared is not None and declared.type == "struct_type"
                else "interface"
                if declared is not None
                else "type"
            )
        qualifier = _scope_names(node, source)
        qualifier = [*package_prefix, *qualifier]
        qualified = ".".join((*qualifier, name))
        counts[qualified] += 1
        records.append(
            {
                "id": f"{path}::{qualified}#{counts[qualified]}",
                "name": name,
                "kind": kind,
                "line": node.start_point[0] + 1,
                "qualifier": ".".join(qualifier),
            }
        )
    return records


def _scope_names(node: Node, source: bytes) -> list[str]:
    scopes = []
    parent = node.parent
    scope_types = {
        "class_declaration",
        "class_definition",
        "class_specifier",
        "struct_specifier",
        "enum_specifier",
        "struct_item",
        "struct_declaration",
        "interface_declaration",
        "enum_declaration",
        "record_declaration",
        "trait_item",
        "module",
        "mod_item",
        "namespace_declaration",
        "namespace_definition",
        "module_declaration",
        "package_declaration",
    }
    while parent is not None:
        if parent.type in scope_types:
            name = parent.child_by_field_name("name")
            if name is not None:
                scopes.append(_node_text(name, source).replace("::", "."))
        parent = parent.parent
    return list(reversed(scopes))


def _function_qualifier(
    node: Node | None, source: bytes, language: str, package_prefix: list[str]
) -> str:
    if node is None:
        return ""
    scopes = _scope_names(node, source)
    if language == "go":
        receiver = node.child_by_field_name("receiver")
        if receiver is not None:
            receiver_text = _node_text(receiver, source)
            match = re.search(r"\b([A-Za-z_]\w*)\s*\*?\s*\)", receiver_text)
            if match:
                scopes.append(match.group(1))
    scopes = [*package_prefix, *scopes]
    return ".".join(scopes)


def _package_prefix(source: bytes, language: str) -> list[str]:
    text = source.decode(errors="replace")
    prefix = []
    if language in {"java", "csharp"}:
        match = (
            re.search(r"\bpackage\s+([\w.]+)\s*;", text) if language == "java" else None
        )
        if match:
            prefix.append(match.group(1))
    if language == "go":
        match = re.search(r"(?m)^\s*package\s+(\w+)", text)
        if match:
            prefix.append(match.group(1))
    return prefix


def _cpp_out_of_line_prefix(node: Node | None, source: bytes) -> str | None:
    if node is None:
        return None
    name = node.child_by_field_name("name")
    if name is None:
        name = node.child_by_field_name("declarator")
        while name is not None and name.type != "qualified_identifier":
            name = name.child_by_field_name("declarator")
    text = _node_text(name, source) if name is not None else ""
    if "::" not in text:
        return None
    return ".".join(text.split("::")[:-1])


def _call_name_and_receiver(
    call: Node, name_node: Node, function_node: Node | None, source: bytes
) -> tuple[str, str | None, str | None]:
    if call.type == "method_invocation":
        object_node = call.child_by_field_name("object")
        name = _node_text(name_node, source)
        return (
            name,
            _normalized_receiver(object_node, source),
            _receiver_chain(_node_text(object_node, source)),
        )
    if function_node is not None and function_node.type in {
        "attribute",
        "member_expression",
        "field_expression",
        "selector_expression",
    }:
        receiver_node = function_node.child_by_field_name("object")
        attr_node = function_node.child_by_field_name("attribute")
        if attr_node is None:
            attr_node = function_node.child_by_field_name("field")
        if attr_node is None:
            attr_node = function_node.child_by_field_name("property")
        if attr_node is None:
            attr_node = function_node.named_children[-1]
        receiver_text = _member_receiver_text(_node_text(function_node, source))
        return (
            _node_text(attr_node, source),
            _normalized_receiver(receiver_node, source),
            receiver_text,
        )
    return (
        _node_text(name_node, source),
        None,
        _member_receiver_text(_node_text(function_node, source)),
    )


def _node_text(node: Node | None, source: bytes) -> str:
    if node is None:
        return ""
    return source[node.start_byte : node.end_byte].decode(errors="replace")


def _normalized_receiver(node: Node | None, source: bytes) -> str | None:
    if node is None:
        return None
    if _node_text(node, source) in {"self", "this", "super"}:
        return "self"
    return None


def _receiver_chain(text: str) -> str | None:
    """Return a plain identifier chain, normalizing member separators."""
    normalized = re.sub(r"\s*(?:\.|::|->)\s*", ".", text)
    if not normalized or not re.fullmatch(
        r"[A-Za-z_$][\w$]*(?:\.[A-Za-z_$][\w$]*)*", normalized
    ):
        return None
    return normalized


def _member_receiver_text(text: str) -> str | None:
    match = re.fullmatch(r"(.+?)\s*(?:\.|::|->)\s*([A-Za-z_$][\w$]*)", text)
    if match is None:
        return None
    return _receiver_chain(match.group(1))


def _argument_count(args: Node | None) -> int:
    if args is None:
        return 0
    if args.type in {"generator_expression", "yield_expression"}:
        return 1
    if args.type in {"argument_list", "arguments", "argument_list_expression"}:
        return sum(1 for child in args.named_children if child.type not in _COMMENTS)
    return 1


def _function_end(record: dict) -> int:
    return record["_end_byte"]


def _name_issues(name: str) -> list[str]:
    issues = []
    normalized = name.strip("_")
    if (
        len(normalized) <= 2
        and normalized
        and normalized.lower()
        not in {"i", "j", "k", "n", "x", "y", "e", "id", "io", "db", "ui", "_"}
    ):
        issues.append("single_char")
    words = re.findall(r"[A-Z]?[a-z]+|[A-Z]+(?=[A-Z]|$)|\d+", normalized)
    lowered = [word.lower() for word in words]
    if any(word in _VAGUE for word in lowered) or normalized.lower() in _VAGUE:
        issues.append("vague")
    if re.search(r"\d+$", name):
        issues.append("numbered")
    if len(words) > 6 or len(normalized) > 40:
        issues.append("long")
    short_unknown_words = {
        word.lower()
        for word in words
        if word.isalpha()
        and len(word) <= 3
        and word.lower() not in _COMMON_WORDS
        and word.lower() not in {"i", "j", "k", "n", "x", "y", "e"}
    }
    if short_unknown_words:
        issues.append("abbreviation")
    return issues


