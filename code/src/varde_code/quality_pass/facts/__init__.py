"""Language-neutral, path-independent L1 facts for the scan-time quality pass.

Language modules may add ``function_node_types``, ``function_node_name`` and
``function_body`` hooks for grammar-specific callable nodes, plus ``markers``
for non-comment generated-code markers. ``suppress_accessor_fallback`` opts out
of the neutral accessor heuristic after language role checks. ``unmeasured_regions``
lists spans whose code tree-sitter cannot measure (macros, templates) and
``filter_name_issues`` drops language-conventional short names; ``overload_pairs``
pairs const and non-const overloads. ``normalize_record`` upgrades a facts-1
record to the facts-2 shape. Missing hooks preserve neutral behavior.
"""

