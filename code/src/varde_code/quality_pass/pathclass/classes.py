"""Pure path classification, kept separate from content-derived facts."""

from __future__ import annotations

import fnmatch
import hashlib
import json
from collections.abc import Iterable
from dataclasses import dataclass
from pathlib import PurePosixPath

_DEFAULT_VENDORED_DIRS = (
    "vendor",
    "vendors",
    "third_party",
    "third-party",
    "node_modules",
    "externals",
)
_DEFAULT_GENERATED_DIRS = ("generated", "autogenerated", "auto-generated")


@dataclass(frozen=True)
class PathPredicates:
    """Path predicates read from the fast index and repo configuration."""

    is_test_path: bool = False
    is_tooling_path: bool = False
    exclusion_globs: tuple[str, ...] = ()
    vendored_dirs: tuple[str, ...] = _DEFAULT_VENDORED_DIRS
    generated_dirs: tuple[str, ...] = _DEFAULT_GENERATED_DIRS
    generated_marker: bool = False
    generator_signature: bool = False
    allowlisted_from_base: bool = False


@dataclass(frozen=True)
class PathClass:
    module: str
    test: bool
    tooling: bool
    generated: bool
    vendored: bool
    excluded: bool
    exclusion_reason: str | None
    scope_reasons: tuple[str, ...]
    version: str


_VERSION_INPUTS = {
    "algorithm_version": 4,
    "test_predicate": "fast-index-is_test_path-v1",
    "tooling_predicate": "fast-index-is_tooling_path-v1",
    "glob_matcher": "posix-fnmatch-root-and-recursive-v2",
    "gate_generated_rule": "marker-needs-convention-signature-or-base-allowlist-v2",
    "module_algorithm": "nearest-supplied-language-package-dir-v2",
    "default_vendored_dirs": _DEFAULT_VENDORED_DIRS,
    "default_generated_dirs": _DEFAULT_GENERATED_DIRS,
}


def path_class_version(
    predicates: PathPredicates | None = None,
    *,
    package_dirs: Iterable[str] = (),
) -> str:
    inputs = dict(_VERSION_INPUTS)
    if predicates is not None:
        inputs["predicate_config"] = {
            "is_test_path": predicates.is_test_path,
            "is_tooling_path": predicates.is_tooling_path,
            "exclusion_globs": predicates.exclusion_globs,
            "vendored_dirs": predicates.vendored_dirs,
            "generated_dirs": predicates.generated_dirs,
            "generated_marker": predicates.generated_marker,
            "generator_signature": predicates.generator_signature,
            "allowlisted_from_base": predicates.allowlisted_from_base,
        }
    inputs["package_dirs"] = sorted(
        {
            PurePosixPath(directory.replace("\\", "/")).as_posix()
            for directory in package_dirs
        }
    )
    payload = json.dumps(inputs, sort_keys=True, separators=(",", ":"))
    return "pathclass-" + hashlib.blake2b(payload.encode(), digest_size=12).hexdigest()


def _matches_glob(path: str, pattern: str) -> bool:
    normalized_pattern = pattern.replace("\\", "/")
    if fnmatch.fnmatchcase(path, normalized_pattern):
        return True
    return normalized_pattern.startswith("**/") and fnmatch.fnmatchcase(
        path, normalized_pattern[3:]
    )


def classify_path(
    path: str,
    predicates: PathPredicates,
    *,
    language: str,
    gate_mode: bool = False,
    package_dirs: Iterable[str] = (),
) -> PathClass:
    """Classify a repository-relative path using path/config predicates."""
    normalized = PurePosixPath(path.replace("\\", "/"))
    parts = normalized.parts
    lower_parts = tuple(part.casefold() for part in parts[:-1])
    vendored_dirs = {item.casefold() for item in predicates.vendored_dirs}
    generated_dirs = {item.casefold() for item in predicates.generated_dirs}
    vendored = any(part in vendored_dirs for part in lower_parts)
    generated_by_convention = any(part in generated_dirs for part in lower_parts)
    generated = (
        generated_by_convention
        or predicates.generated_marker
        or predicates.generator_signature
    )
    test = predicates.is_test_path
    tooling = predicates.is_tooling_path
    glob_excluded = any(
        _matches_glob(normalized.as_posix(), pattern)
        for pattern in predicates.exclusion_globs
    )
    marker_only = predicates.generated_marker and not (
        generated_by_convention or predicates.generator_signature
    )
    if gate_mode and marker_only and not predicates.allowlisted_from_base:
        generated = False
    exclusion_reason = None
    if vendored:
        exclusion_reason = "vendored directory convention"
    elif glob_excluded:
        exclusion_reason = "configured exclusion glob"
    elif generated and (
        not gate_mode or not marker_only or predicates.allowlisted_from_base
    ):
        if marker_only and predicates.allowlisted_from_base:
            exclusion_reason = "base-ref generated allowlist"
        elif marker_only:
            exclusion_reason = "generated marker"
        elif predicates.generator_signature:
            exclusion_reason = "recognized generator signature"
        else:
            exclusion_reason = "generated directory convention"
    excluded = exclusion_reason is not None
    scope_reasons = tuple(
        reason
        for active, reason in (
            (test, "fast-index test path predicate"),
            (tooling, "fast-index tooling path predicate"),
        )
        if active
    )
    return PathClass(
        module=module_of(path, language=language, package_dirs=package_dirs),
        test=test,
        tooling=tooling,
        generated=generated,
        vendored=vendored,
        excluded=excluded,
        exclusion_reason=exclusion_reason,
        scope_reasons=scope_reasons,
        version=path_class_version(predicates, package_dirs=package_dirs),
    )


def module_of(
    path: str,
    *,
    language: str,
    package_dirs: Iterable[str] = (),
) -> str:
    """Return nearest language package directory, else the parent.

    ``package_dirs`` comes from package markers in the repository file list and
    must contain only directories for the requested language.
    """
    normalized = PurePosixPath(path.replace("\\", "/"))
    parent = normalized.parent
    parts = parent.parts
    if not parts or str(parent) == ".":
        return "."
    candidate_dirs = {
        str(PurePosixPath(directory.replace("\\", "/"))) for directory in package_dirs
    }
    for candidate in (parent, *parent.parents):
        if str(candidate) in candidate_dirs:
            return str(candidate)
    return str(parent)
